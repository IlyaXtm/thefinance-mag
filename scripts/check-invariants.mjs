#!/usr/bin/env node
/**
 * Assert the rendering invariants from CLAUDE.md against a running build.
 *
 *   npm run check:invariants -- http://127.0.0.1:3000
 *
 * Exits non-zero on the first failed assertion. That is the whole point.
 *
 * ── Why this file exists ────────────────────────────────────────────────
 *
 * The previous version of this check PRINTED a table of numbers and then
 * printed "All invariants hold" unconditionally. It shipped in
 * reports/performance.txt showing `eager 0` on three routes, directly beneath
 * a stated invariant of "exactly one eager image per page". Nothing failed,
 * because nothing could fail. An invariant that prints is a log line.
 *
 * ── And why it takes a URL instead of hardcoding one ─────────────────────
 *
 * That same report was generated by two scripts pointing at two different
 * ports — one at the build under test, one at a server left running from an
 * earlier build. The perf numbers were current and the invariant numbers were
 * three commits stale, in the same file, and the contradiction shipped.
 *
 * So: the base URL is an argument, and `assertBuildMatches` refuses to run
 * against a server whose /mag/health buildId is not the one in .next/BUILD_ID
 * on disk. Measuring the wrong server is now an error, not a footnote.
 */

import { readFileSync } from 'node:fs';
import { chromium } from 'playwright-core';

const BASE = process.argv[2] ?? process.env.BASE_URL;
if (!BASE) {
  console.error('usage: node scripts/check-invariants.mjs <base-url>');
  process.exit(2);
}

const ROUTES = [
  '/mag',
  '/mag/archive',
  '/mag/news',
  '/mag/fundamental-analysis',
  '/mag/market/crypto',
];

/* News rows carry 78px thumbnails that are below the fold on every viewport
   and are not the LCP element — the standfirst is. Requiring an eager image
   there would preload something no reader sees first. */
const NO_EAGER_IMAGE = new Set(['/mag/news']);

const failures = [];
const rows = [];

function check(route, name, ok, detail) {
  if (!ok) failures.push(`${route}: ${name} — ${detail}`);
  return ok;
}

/**
 * Refuse to measure a server that is not running the build on disk.
 *
 * Compares `/mag/health`'s `buildId` against `.next/BUILD_ID`. Both come from
 * the same constant in next.config.ts, so they agree exactly or the server is
 * running something else.
 *
 * AN EARLIER VERSION OF THIS GUARD COMPARED ASSET HASHES AND DID NOT WORK.
 * Next reuses chunk and stylesheet filenames when a change does not alter the
 * emitted bundles — a prop added to one component left every hash identical,
 * so the guard passed against a demonstrably stale server. It was shipping the
 * exact false confidence this file exists to remove, so it was replaced rather
 * than patched.
 */
async function assertBuildMatches() {
  let onDisk;
  try {
    onDisk = readFileSync('.next/BUILD_ID', 'utf8').trim();
  } catch {
    console.error('Cannot read .next/BUILD_ID — run `next build` first.');
    process.exit(2);
  }

  let served;
  try {
    const res = await fetch(`${BASE}/mag/health`);
    served = (await res.json()).buildId;
  } catch (err) {
    console.error(`Cannot reach ${BASE}/mag/health: ${err.message}`);
    process.exit(2);
  }

  if (served !== onDisk) {
    console.error(
      `\n✗ ${BASE} is serving a DIFFERENT build.\n` +
        `  server:  ${served}\n` +
        `  on disk: ${onDisk}\n` +
        `  Restart it against the current build before measuring.\n`,
    );
    process.exit(2);
  }
}

await assertBuildMatches();

const browser = await chromium.launch({
  executablePath: process.env.CHROMIUM_PATH ?? '/opt/pw-browsers/chromium',
});

for (const route of ROUTES) {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const hosts = new Set();
  page.on('request', (r) => {
    try {
      hosts.add(new URL(r.url()).host);
    } catch {
      /* data: and blob: URLs have no host and are not third parties. */
    }
  });

  const res = await page.goto(BASE + route, { waitUntil: 'networkidle' });

  check(route, 'HTTP 200', res?.status() === 200, `got ${res?.status()}`);

  const d = await page.evaluate(() => {
    const imgs = [...document.querySelectorAll('img')];
    const levels = [...document.querySelectorAll('h1,h2,h3,h4,h5,h6')].map((h) => +h.tagName[1]);
    let skips = 0;
    for (let i = 1; i < levels.length; i += 1) if (levels[i] - levels[i - 1] > 1) skips += 1;
    return {
      eager: imgs.filter((i) => i.loading !== 'lazy').length,
      lazy: imgs.filter((i) => i.loading === 'lazy').length,
      noSizes: imgs.filter((i) => !i.getAttribute('sizes')).length,
      noAlt: imgs.filter((i) => i.getAttribute('alt') === null).length,
      h1: document.querySelectorAll('h1').length,
      skips,
      fontPreload: !!document.querySelector('link[rel="preload"][as="font"]'),
      overflow: document.documentElement.scrollWidth > window.innerWidth,
    };
  });

  const wantEager = NO_EAGER_IMAGE.has(route) ? 0 : 1;
  const third = [...hosts].filter((h) => !BASE.includes(h));

  const ok = [
    check(route, 'exactly one eager image', d.eager === wantEager, `eager=${d.eager}, want ${wantEager}`),
    check(route, 'every image has sizes', d.noSizes === 0, `${d.noSizes} without sizes`),
    check(route, 'every image has alt', d.noAlt === 0, `${d.noAlt} without alt`),
    check(route, 'exactly one <h1>', d.h1 === 1, `${d.h1} found`),
    check(route, 'no heading-level skips', d.skips === 0, `${d.skips} skip(s)`),
    check(route, 'font preloaded', d.fontPreload, 'no preload link'),
    check(route, 'no third-party requests', third.length === 0, third.join(', ')),
    check(route, 'no horizontal overflow', !d.overflow, 'scrollWidth exceeds viewport'),
  ].every(Boolean);

  rows.push(
    `${ok ? 'PASS' : 'FAIL'}  ${route.padEnd(28)} eager=${d.eager} lazy=${String(d.lazy).padStart(2)} ` +
      `h1=${d.h1} skips=${d.skips} sizes✓=${d.noSizes === 0} alt✓=${d.noAlt === 0} ` +
      `font✓=${d.fontPreload} 3p=${third.length}`,
  );

  await page.close();
}

/* 390px is the viewport CLAUDE.md's overflow rule is written against. */
for (const route of ROUTES) {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
  await page.goto(BASE + route, { waitUntil: 'networkidle' });
  const over = await page.evaluate(
    () => document.documentElement.scrollWidth > window.innerWidth,
  );
  check(route, 'no horizontal overflow at 390px', !over, 'scrollWidth exceeds viewport');
  await page.close();
}

await browser.close();

console.log(`\nInvariants — ${BASE}\n`);
for (const r of rows) console.log('  ' + r);

if (failures.length) {
  console.error(`\n✗ ${failures.length} invariant failure(s):\n`);
  for (const f of failures) console.error('  - ' + f);
  console.error('');
  process.exit(1);
}

console.log(`\n✓ all invariants hold across ${ROUTES.length} routes\n`);
